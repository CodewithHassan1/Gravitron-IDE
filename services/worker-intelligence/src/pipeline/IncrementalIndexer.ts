import * as crypto from 'crypto';
import * as path from 'path';
import { IParser } from '../domain/IParser';
import { SnapshotModel } from '../db/SnapshotModel';
import { FileDTO, EmbeddingDTO, SymbolKind } from '../domain/IndexDTOs';
import { IEmbeddingProvider } from '../domain/IEmbeddingProvider';
import { randomUUID } from 'crypto';

export type IndexEvent =
  | { type: 'update'; workspaceRoot: string; filePath: string; content: string; version: number }
  | { type: 'delete'; workspaceRoot: string; filePath: string; version: number };

export class IncrementalIndexer {
  // Track the highest version processed per file to prevent stale updates
  private latestProcessedVersion: Map<string, number> = new Map();

  // Queued jobs (debounced by filepath)
  private queue: Map<string, IndexEvent> = new Map();
  private processing: boolean = false;

  private excludePatterns: string[] = ['node_modules', '.git', 'dist', 'build', '.DS_Store'];

  constructor(
    private parser: IParser,
    private model: SnapshotModel,
    private embeddingProvider?: IEmbeddingProvider
  ) {}

  /**
   * Queue a file update. Rapid updates to the same file are coalesced.
   */
  public queueUpdate(
    workspaceRoot: string,
    filePath: string,
    content: string,
    version: number
  ): void {
    if (this.isExcluded(filePath)) return;
    this.queue.set(filePath, { type: 'update', workspaceRoot, filePath, content, version });
    this.scheduleProcessing();
  }

  /**
   * Queue a file deletion.
   */
  public queueDelete(workspaceRoot: string, filePath: string, version: number): void {
    if (this.isExcluded(filePath)) return;
    this.queue.set(filePath, { type: 'delete', workspaceRoot, filePath, version });
    this.scheduleProcessing();
  }

  private isExcluded(filePath: string): boolean {
    const parts = filePath.split(/[/\\]/);
    return parts.some((part) => this.excludePatterns.includes(part));
  }

  private scheduleProcessing() {
    if (!this.processing) {
      this.processing = true;
      // Use setImmediate to allow coalescing of rapid synchronous calls
      setImmediate(() => this.processQueue());
    }
  }

  private async processQueue() {
    while (this.queue.size > 0) {
      // Pick the first item
      const [filePath, event] = this.queue.entries().next().value;
      this.queue.delete(filePath);

      try {
        await this.processEvent(event);
      } catch (err) {
        // Failed parsing never destroys the last known-good index (rollback is handled in SQLiteStore)
        // Parser diagnostics do not crash the scheduler
        console.error(`Indexer error processing ${filePath}:`, err);
      }
    }
    this.processing = false;
  }

  public async processEvent(event: IndexEvent): Promise<void> {
    const { filePath, version } = event;
    const currentMaxVersion = this.latestProcessedVersion.get(filePath) || 0;

    // Stale update prevention: v1 completing after v2 must not overwrite v2
    if (version < currentMaxVersion) {
      console.log(`Skipping stale update for ${filePath} (v${version} < v${currentMaxVersion})`);
      return; // Ignore stale
    }

    if (event.type === 'delete') {
      // Deletes the complete file index transactionally
      await this.model.deleteFile(filePath);
      this.latestProcessedVersion.set(filePath, version);
    } else {
      // Path bounding check again just in case
      const resolvedRoot = path.resolve(event.workspaceRoot);
      const resolvedFile = path.resolve(resolvedRoot, filePath);
      const relPath = path.relative(resolvedRoot, resolvedFile);
      if (relPath.startsWith('..') || path.isAbsolute(relPath)) {
        throw new Error(`Path traversal blocked: ${filePath} is outside workspace root`);
      }

      // Parse (pure computation)
      const parsed = this.parser.parse(event.workspaceRoot, filePath, event.content);

      const fileDto: FileDTO = {
        id: '', // Generated by store
        workspaceId: this.model.getWorkspaceId(),
        filePath,
        hash: this.hashContent(event.content),
        updatedAt: Date.now(),
      };

      // Ensure that if it somehow took a long time to parse, we check version again
      const maxVersAfterParse = this.latestProcessedVersion.get(filePath) || 0;
      if (version < maxVersAfterParse) {
        return; // A newer version came and committed while we were parsing
      }

      // Generate Semantic Chunks based on symbols
      const embeddings: EmbeddingDTO[] = [];
      if (this.embeddingProvider) {
        try {
          // Create meaningful chunks based on top-level symbols (Classes, Functions, Interfaces)
          const chunks = parsed.symbols.filter(
            (s) =>
              s.kind === SymbolKind.Class ||
              s.kind === SymbolKind.Function ||
              s.kind === SymbolKind.Interface ||
              s.kind === SymbolKind.Method
          );

          for (const chunk of chunks) {
            if (chunk.snippet) {
              const vector = await this.embeddingProvider.embed(chunk.snippet);
              embeddings.push({
                id: randomUUID(),
                workspaceId: this.model.getWorkspaceId(),
                fileId: fileDto.id,
                chunkId: randomUUID(),
                content: chunk.snippet,
                vector,
                symbolName: chunk.name,
              });
            }
          }
          // If no symbols found, we could chunk by file content, but for now we skip.
        } catch (err) {
          console.error(`Failed to generate embeddings for ${filePath}:`, err);
          // Proceed anyway to preserve structural index (per rule 11)
        }
      }

      // Atomic SQLite transaction
      await this.model.commitFile(
        fileDto,
        parsed.symbols,
        parsed.references,
        parsed.imports,
        embeddings
      );
      this.latestProcessedVersion.set(filePath, version);
    }
  }

  private hashContent(content: string): string {
    return crypto.createHash('sha256').update(content).digest('hex');
  }

  /**
   * For testing purposes, wait until queue is empty
   */
  public async drain(): Promise<void> {
    while (this.processing || this.queue.size > 0) {
      await new Promise((resolve) => setTimeout(resolve, 10));
    }
  }
}
